"""List the Substack essays for the page, with the opening of each.

Substack is the source of truth: every post in the feed is shown, newest
first, with its title, subtitle, date and the first few paragraphs, which the
page sets on the stage as a preview. Run this again after publishing.

usage: python3 tools/essays/feed.py
writes prototype/page/essays.js
"""
import html
import json
import re
import urllib.request
import xml.etree.ElementTree as ET
from email.utils import parsedate_to_datetime

FEED = 'https://guillermobasterra.substack.com/feed'
CONTENT = '{http://purl.org/rss/1.0/modules/content/}encoded'
OPENING = 1100                                  # characters of the essay to carry, to the nearest paragraph
SKIP = ('subscribe', 'thanks for reading')      # Substack's own boilerplate paragraphs


def opening(body):
    """The first paragraphs of the post as plain text, up to OPENING characters."""
    out, size = [], 0
    for p in re.findall(r'<p[^>]*>(.*?)</p>', body, re.S):
        text = re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', p))).strip()
        if not text or any(s in text.lower() for s in SKIP):
            continue
        out.append(text)
        size += len(text)
        if size >= OPENING:
            break
    return out


request = urllib.request.Request(FEED, headers={'User-Agent': 'Mozilla/5.0'})
root = ET.fromstring(urllib.request.urlopen(request).read())
essays = []
for item in root.iter('item'):
    when = parsedate_to_datetime(item.findtext('pubDate'))
    essays.append(dict(
        title=item.findtext('title').strip(),
        subtitle=(item.findtext('description') or '').strip(),
        link=item.findtext('link').strip(),
        date=when.strftime('%B %Y').lower(),
        year=when.year,
        opening=opening(item.findtext(CONTENT) or ''),
    ))
    print(f'{when:%Y-%m-%d}  {essays[-1]["title"]}')

with open('prototype/page/essays.js', 'w') as f:
    f.write('// Generated by tools/essays/feed.py from the Substack feed. Do not edit.\n')
    f.write('window.ESSAYS = ' + json.dumps(essays, ensure_ascii=False, indent=1) + ';\n')
